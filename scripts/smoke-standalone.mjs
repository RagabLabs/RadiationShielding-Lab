import { JSDOM, VirtualConsole } from 'jsdom';
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const errors=[];const console=new VirtualConsole();console.on('jsdomError',e=>errors.push(String(e)));console.on('error',e=>errors.push(String(e)));
const html=await readFile('dist/START-HERE.html','utf8');
assert(!html.includes('<script src='),'Standalone cannot require external scripts');
const dom=new JSDOM(html,{runScripts:'dangerously',pretendToBeVisual:true,url:'https://offline.invalid/#complete',virtualConsole:console,beforeParse(window){window.scrollTo=()=>{};}});
await new Promise(r=>setTimeout(r,250));
const doc=dom.window.document;
assert.equal(doc.querySelector('h1')?.textContent,'Complete shielding analysis');
assert.equal(doc.querySelectorAll('nav button').length,15);
assert(doc.querySelectorAll('.chart-card svg').length>=6);
assert(!doc.querySelector('[role=alert]'));
const themes=doc.querySelector('[aria-label="Toggle color theme"]');themes.click();await new Promise(r=>setTimeout(r,30));assert.equal(doc.documentElement.dataset.theme,'light');
const lang=doc.querySelector('[aria-label="Switch language"]');lang.click();await new Promise(r=>setTimeout(r,30));assert.equal(doc.documentElement.dir,'rtl');
assert.equal(errors.length,0,errors.join('\n'));
const report={timestamp:new Date().toISOString(),environment:'jsdom; built inline bundle executed; not a browser engine',passed:true,checks:['self-contained inline scripts','application startup','15 navigation pages','scientific SVG output','no startup error','theme switch','Arabic RTL switch'],errors};
await writeFile('reports/standalone-smoke.json',JSON.stringify(report,null,2)+'\n');
process.stdout.write(JSON.stringify(report,null,2)+'\n');dom.window.close();
